import { chromium } from '@playwright/test';
const [out] = process.argv.slice(2);
const base = process.env.BASE_URL ?? 'http://127.0.0.1:2112';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(base + '/dang-nhap');
await p.fill('input[autocomplete=username]', 'quanly'); await p.fill('input[autocomplete=current-password]', 'Demo@123456');
await p.click('button[type=submit]'); await p.waitForURL((u) => !u.pathname.startsWith('/dang-nhap'));
await p.goto(base + '/tao-de'); await p.waitForLoadState('networkidle');
await p.getByLabel('Tên đề thi').fill('Sát hạch kỹ sư thiết kế PV – Đợt 1');
await p.screenshot({ path: `${out}/builder1.png`, fullPage: true });
await p.getByRole('button', { name: 'Tiếp' }).click();
await p.waitForTimeout(800);
await p.getByRole('button', { name: 'Sinh đề tự động' }).click();
await p.waitForTimeout(2000);
await p.screenshot({ path: `${out}/builder2.png`, fullPage: true });
await p.getByRole('button', { name: 'Tiếp' }).click();
await p.waitForTimeout(800);
await p.getByRole('button', { name: 'Phát hành đề thi' }).click();
await p.waitForURL(/\/de-thi\//); await p.waitForTimeout(1500);
console.log('exam url', p.url());
await p.screenshot({ path: `${out}/exam-detail.png`, fullPage: true });
console.log(errs.length ? 'ERRORS ' + errs.join('\n') : 'no errors');
await b.close();
